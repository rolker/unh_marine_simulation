"""
Build the demo's rqt perspective from the roster, and decide how rqt is started on it.

The perspective file (``config/demo.perspective``) holds the Survey Coverage plugin and one Ping
Profile plugin per roster boat. It is generated by ``python3 -m marine_simulation.demo_perspective
<roster> <output>`` and checked against the roster by a test, so a boat added to the roster cannot
leave the display behind.

How rqt treats ``--perspective-file`` (read from ``qt_gui/main.py`` and
``qt_gui/perspective_manager.py`` of Jazzy, and checked live): the file is imported as a HIDDEN
perspective named ``@`` plus the file's basename, extension included (``@demo.perspective``). An
existing perspective of that name is removed and replaced, and a hidden one is not added to the
menu and is not made the ``current-perspective``. It is saved in the operator's ``rqt_gui.ini``
when rqt exits, like any other, so ``--perspective @demo.perspective`` finds it afterwards and
rqt keeps its geometry per perspective. This module therefore starts rqt with the file on a first
start (the name is not stored in ``rqt_gui.ini`` yet) or when asked, and by that name after. The
demo launch does not import ``config/demo.perspective`` itself but a copy generated for the boats
that are run, named by a hash of its content (``generated_file``), so a different set of boats
or a changed layout is a first start by itself.

Nothing here imports ROS, Qt or ``launch``.
"""

import csv
import hashlib
import json
import os
import sys
from typing import List, Optional, Sequence, Tuple

import yaml

PERSPECTIVE_FILE_NAME = 'demo.perspective'
HIDDEN_PREFIX = '@'                 # qt_gui.perspective_manager.PerspectiveManager.HIDDEN_PREFIX
COVERAGE_PLUGIN_ID = 'rqt_coverage/rqt_coverage/CoveragePlugin'
PING_PROFILE_PLUGIN_ID = 'rqt_ping_profile/rqt_ping_profile/PingProfilePlugin'
COVERAGE_TOPIC = 'coverage_assessment'
# 0 to 30 m of water below the transducer. CAMP's live coverage layer shows the same 30 m of
# water at Portsmouth, but in ellipsoid heights (demo_camp_profile.conf), so the numbers differ.
DEPTH_MIN = 0.0
DEPTH_MAX = 30.0
RQT_SETTINGS_RELATIVE = os.path.join('ros.org', 'rqt_gui.ini')


def detections_topic(boat_name: str) -> str:
    """Return the full multibeam topic of a boat (the namespace is the boat's name)."""
    return '/%s/sensors/mbes/detections' % boat_name


def _plugin_group(title: str, config_yaml: str) -> dict:
    """Return the settings group qt_gui keeps for one plugin instance."""
    return {
        'keys': {},
        'groups': {
            'dock_widget__': {'keys': {'dock_widget_title': _repr(title)}, 'groups': {}},
            'plugin': {'keys': {'config_yaml': _repr(config_yaml)}, 'groups': {}},
        },
    }


def _repr(value) -> dict:
    """Return a value as ``PerspectiveManager._export_value`` writes a plain Python value."""
    return {'type': 'repr', 'repr': repr(value)}


def instance_name(plugin_id: str, serial: int) -> str:
    """Return the settings group name of a plugin instance (``PluginInstanceId.tidy_str``)."""
    return 'plugin__%s__%d' % (plugin_id.replace('/', '__'), serial)


def ping_profile_config(boat_name: str) -> str:
    """Return the YAML ``rqt_ping_profile`` keeps in ``config_yaml``; the rest are defaults."""
    return yaml.safe_dump({'topic': detections_topic(boat_name), 'title': boat_name,
                           'depth_mode': 'fixed', 'depth_min': DEPTH_MIN,
                           'depth_max': DEPTH_MAX}, sort_keys=True)


def build_perspective(boat_names: Sequence[str]) -> dict:
    """
    Return the perspective, in the ``.perspective`` JSON structure, for the boats in order.

    No main-window geometry or dock state is included: those belong to the monitor, and rqt
    lays the docks out itself and then keeps what the operator changes.
    """
    plugins = {COVERAGE_PLUGIN_ID: [1],
               PING_PROFILE_PLUGIN_ID: list(range(1, len(boat_names) + 1))}
    groups = {instance_name(COVERAGE_PLUGIN_ID, 1): _plugin_group(
        'Survey Coverage', yaml.safe_dump({'topic': COVERAGE_TOPIC}, sort_keys=True))}
    for serial, name in enumerate(boat_names, start=1):
        groups[instance_name(PING_PROFILE_PLUGIN_ID, serial)] = _plugin_group(
            name, ping_profile_config(name))
    return {'keys': {}, 'groups': {'pluginmanager': {
        'keys': {'running-plugins': _repr(plugins)}, 'groups': groups}}}


def perspective_text(boat_names: Sequence[str]) -> str:
    """Return the file text for the boats (what ``rqt`` writes: indent 2, trailing newline)."""
    return json.dumps(build_perspective(boat_names), indent=2, separators=(',', ': '),
                      sort_keys=True) + '\n'


def generated_file(boat_names: Sequence[str], directory: str) -> str:
    """
    Write the perspective for the boats into ``directory`` and return its path.

    The file name carries a hash of the content (``demo-<8 hex>.perspective``), and rqt names an
    import by the file name, so each set of boats (and each version of this module's layout) has
    its own stored perspective: a roster change, ``--boats`` or ``--roster`` starts on a fresh
    import by itself, and what the operator rearranged is kept per set. The file is written
    to a temporary name and renamed, so a reader never sees half of it.
    """
    text = perspective_text(boat_names)
    digest = hashlib.sha256(text.encode('utf-8')).hexdigest()[:8]
    path = os.path.join(directory, 'demo-%s.perspective' % digest)
    try:
        with open(path, encoding='utf-8') as f:
            if f.read() == text:
                return path
    except OSError:
        pass
    os.makedirs(directory, exist_ok=True)
    temporary = '%s.%d.tmp' % (path, os.getpid())
    with open(temporary, 'w', encoding='utf-8') as f:
        f.write(text)
    os.replace(temporary, path)
    return path


def imported_name(perspective_file: str) -> str:
    """Return the name rqt gives a perspective imported with ``--perspective-file``."""
    return HIDDEN_PREFIX + os.path.basename(perspective_file)


def rqt_settings_file(environ: Optional[dict] = None) -> str:
    """Return the path of the operator's rqt settings (QSettings, ``ros.org/rqt_gui.ini``)."""
    environ = os.environ if environ is None else environ
    base = environ.get('XDG_CONFIG_HOME') or os.path.join(
        environ.get('HOME') or os.path.expanduser('~'), '.config')
    return os.path.join(base, RQT_SETTINGS_RELATIVE)


def has_perspective(settings_file: str, name: str) -> bool:
    """
    Return whether rqt has stored the perspective ``name`` in ``settings_file``.

    Two signs count. The ``perspectives`` key of ``[General]`` lists the names as plain text
    (a name starting with ``@`` is stored as ``@@``), but Qt writes that list as a binary
    ``@Variant(...)`` as soon as a name needs it, which the live check showed for
    ``@demo.perspective`` itself; so the keys of the ``[perspective]`` section, which start with
    the percent-escaped name and a backslash, count as well. A file that does not exist is a
    first start (False); one that cannot be read raises ``OSError`` so the caller can say so.
    """
    try:
        with open(settings_file, encoding='utf-8', errors='replace') as f:
            lines = f.read().splitlines()
    except FileNotFoundError:
        return False
    escaped = name.replace('%', '%25').replace('@', '%40') + '\\'
    section = 'General'
    for line in lines:
        stripped = line.strip()
        if stripped.startswith('[') and stripped.endswith(']'):
            section = stripped[1:-1]
        elif section == 'General' and stripped.startswith('perspectives='):
            value = stripped[len('perspectives='):]
            if not value.startswith('@Variant('):
                names = next(csv.reader([value], skipinitialspace=True), [])
                if name in [n[1:] if n.startswith('@@') else n for n in names]:
                    return True
        elif section == 'perspective' and stripped.startswith(escaped):
            return True
    return False


_FRESH_APPLIED: List[bool] = []   # set once --rqt-fresh has been honoured in this process


def rqt_arguments(perspective_file: str, fresh: bool,
                  settings_file: Optional[str] = None) -> Tuple[List[str], str]:
    """
    Return the rqt arguments for the demo perspective, and one line saying which way and why.

    The file is imported on a first start (rqt has no perspective of the imported name yet) or
    with ``fresh`` (``--rqt-fresh``, honoured once per process like ``--camp-fresh``: a restart
    of the group must keep what the operator changed); otherwise rqt is started on the stored
    perspective by name. Raises ``ValueError`` when the file does not exist.
    """
    if not perspective_file or not os.path.isfile(perspective_file):
        raise ValueError('the rqt perspective file %r does not exist' % perspective_file)
    settings_file = settings_file or rqt_settings_file()
    name = imported_name(perspective_file)
    try:
        known = has_perspective(settings_file, name)
    except OSError as exc:
        raise ValueError('cannot read the rqt settings %s: %s' % (settings_file, exc))
    fresh = fresh and not _FRESH_APPLIED
    if fresh or not known:
        why = 'asked for (--rqt-fresh)' if fresh else (
            'first start, %s has no perspective %s' % (settings_file, name))
        if fresh:
            _FRESH_APPLIED.append(True)
        return (['--perspective-file', perspective_file],
                'rqt: importing %s (%s)' % (perspective_file, why))
    return (['--perspective', name],
            'rqt: starting on the stored perspective %s of %s' % (name, settings_file))


def main(argv: Optional[Sequence[str]] = None) -> int:
    """Write the perspective for a roster: ``demo_perspective.py <roster.yaml> <output>``."""
    from marine_simulation import roster
    argv = sys.argv[1:] if argv is None else argv
    if len(argv) != 2:
        print('usage: python3 -m marine_simulation.demo_perspective <roster.yaml> <output>',
              file=sys.stderr)
        return 2
    names = [boat.name for boat in roster.load_roster(argv[0])]
    with open(argv[1], 'w', encoding='utf-8') as f:
        f.write(perspective_text(names))
    return 0


if __name__ == '__main__':
    sys.exit(main())
